// неоновая вывеска MOTEL + VACANCY, мигающая
const neonOn = t => Math.sin(t * 3) > -0.7 || Math.sin(t * 17) > 0.6;
function drawSign(ctx, t) {
  const on = neonOn(t);
  R(ctx, 586, 236, 4, 30, '#5a5a62');
  R(ctx, 522, 212, 112, 28, '#1a1418'); R(ctx, 522, 212, 112, 2, '#3a3038'); R(ctx, 524, 214, 108, 24, '#241c22');
  const pink = on ? '#ff5a8a' : '#5a2a3a';
  pText(ctx, 'MOTEL', 578 - pTextW('MOTEL', 3) / 2 | 0, 217, pink, 3);
  if (on) glow(ctx, 578, 224, 70, 'rgba(255,60,120,A)', 0.35);
  const vac = Math.sin(t * 1.3) > -0.2;
  pText(ctx, 'VACANCY', 578 - pTextW('VACANCY') / 2 | 0, 233, vac ? '#6aff8a' : '#2a4a32', 1);
  if (vac) glow(ctx, 578, 235, 24, 'rgba(80,255,120,A)', 0.2);
}

