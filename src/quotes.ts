const DAY_MS = 86400000;

/** Номер фразы дня: идёт по кругу, чтобы фразы не повторялись, пока не закончится список. */
export function quoteOfDay(date: Date) {
  const day = Math.floor((date.getTime() - date.getTimezoneOffset() * 60000) / DAY_MS);
  return ((day % QUOTES.length) + QUOTES.length) % QUOTES.length;
}
